package com.fxsoundlite.app

import org.json.JSONArray
import org.json.JSONObject
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo
import java.io.IOException
import java.net.URLEncoder
import kotlin.math.abs

/**
 * Looks up song lyrics on LRCLIB (lrclib.net, a free community lyrics database, no API key).
 * Time-synced lyrics are used when available (the player highlights the current line), otherwise
 * the plain text. When LRCLIB has nothing and the song is a YouTube video, its captions (subtitles,
 * manual or auto-generated) are shown the same way. Blocking: call from a background thread.
 */
object LyricsApi {
    class Line(val timeMs: Long, val text: String)
    class Result(val plain: String, val synced: List<Line>)

    private const val BASE = "https://lrclib.net/api"
    private const val UA = "StarrySound/1.0 (Android)"
    private val cache = object : LinkedHashMap<String, Result>(16, 0.75f, true) {
        override fun removeEldestEntry(e: MutableMap.MutableEntry<String, Result>?) = size > 24
    }

    @Synchronized
    fun cached(key: String): Result? = cache[key]

    /** Returns null when nothing was found; throws [IOException] when the network fails. */
    fun fetch(key: String, title: String, artist: String, durationMs: Long, videoId: String = ""): Result? {
        cached(key)?.let { return it }
        val (t, a) = guess(title, artist)
        val sec = (durationMs / 1000).toInt()
        val found: Result? =
            ((if (a.isNotBlank()) exact(t, a, sec) else null)
                ?: search("$a $t".trim(), sec)
                ?: (if (a.isNotBlank()) search(t, sec) else null))
                ?: (if (videoId.isNotBlank()) runCatching { captions(videoId) }.getOrNull() else null)
        if (found != null) synchronized(this) { cache[key] = found }
        return found
    }

    // ---------------------------------------------------------------- queries

    private fun get(path: String): Http.Response =
        Http.request("GET", "$BASE/$path", mapOf("User-Agent" to UA))

    private fun enc(s: String) = URLEncoder.encode(s, "UTF-8")

    private fun exact(title: String, artist: String, sec: Int): Result? {
        val dur = if (sec > 0) "&duration=$sec" else ""
        val r = get("get?track_name=${enc(title)}&artist_name=${enc(artist)}$dur")
        if (r.code != 200) return null
        return toResult(JSONObject(r.body))
    }

    private fun search(q: String, sec: Int): Result? {
        if (q.isBlank()) return null
        val r = get("search?q=${enc(q)}")
        if (r.code != 200) return null
        val arr = JSONArray(r.body)
        val items = (0 until arr.length()).mapNotNull { arr.optJSONObject(it) }
        val ordered = if (sec > 0) items.sortedBy { abs(it.optDouble("duration", 0.0) - sec) } else items
        // Skip a result whose length is way off: it is a different recording.
        for (o in ordered) {
            if (sec > 0 && abs(o.optDouble("duration", 0.0) - sec) > 15) continue
            toResult(o)?.let { return it }
        }
        return null
    }

    private fun toResult(o: JSONObject): Result? {
        val synced = parseLrc(o.optString("syncedLyrics", ""))
        val plain = o.optString("plainLyrics", "").trim()
        if (synced.isEmpty() && plain.isEmpty()) return null
        return Result(plain.ifEmpty { synced.joinToString("\n") { it.text } }, synced)
    }

    // ---------------------------------------------------------------- YouTube captions (fallback)

    /** Captions of a YouTube video as time-synced lines; null when it has none. */
    private fun captions(videoId: String): Result? {
        val info = StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$videoId")
        val subs = info.subtitles.filter { it.isUrl && !it.content.isNullOrBlank() }
        if (subs.isEmpty()) return null
        // Manual captions beat auto-generated ones; WebVTT beats the other formats.
        val ordered = subs.sortedWith(compareBy({ it.isAutoGenerated }, { it.format != MediaFormat.VTT }))
        for (sub in ordered.take(2)) {
            val r = Http.request("GET", sub.content, mapOf("User-Agent" to UA))
            if (r.code != 200) continue
            val lines = parseCaptions(r.body)
            if (lines.isNotEmpty()) return Result(lines.joinToString("\n") { it.text }, lines)
        }
        return null
    }

    private val VTT_TIME = Regex("(?:(\\d+):)?(\\d{1,2}):(\\d{2})[.,](\\d{3})\\s*-->")
    private val XML_P = Regex("<p\\s[^>]*?(?:begin=\"([^\"]+)\"|\\bt=\"(\\d+)\")[^>]*>(.*?)</p>", RegexOption.DOT_MATCHES_ALL)
    private val TAG = Regex("<[^>]*>")

    private fun clean(s: String): String =
        android.text.Html.fromHtml(s.replace(TAG, ""), 0).toString().replace("\u00A0", " ").trim()

    private fun parseCaptions(body: String): List<Line> {
        val out = ArrayList<Line>()
        var last = ""
        fun add(ms: Long, text: String) {
            for (l in text.lines().map { clean(it) }) {
                if (l.isEmpty() || l == last) continue
                out += Line(ms, l); last = l
            }
        }
        if (body.trimStart().startsWith("WEBVTT")) {
            val ls = body.lines()
            var i = 0
            while (i < ls.size) {
                val m = VTT_TIME.find(ls[i])
                if (m == null) { i++; continue }
                val ms = (m.groupValues[1].ifEmpty { "0" }.toLong() * 3600 + m.groupValues[2].toLong() * 60 +
                    m.groupValues[3].toLong()) * 1000 + m.groupValues[4].toLong()
                val sb = StringBuilder()
                i++
                while (i < ls.size && ls[i].isNotBlank()) { sb.append(ls[i]).append('\n'); i++ }
                add(ms, sb.toString())
            }
        } else {
            for (m in XML_P.findAll(body)) {
                val begin = m.groupValues[1]
                val ms = if (begin.isNotEmpty()) {
                    val p = begin.removeSuffix("s").split(':')
                    if (p.size == 3) ((p[0].toLong() * 3600 + p[1].toLong() * 60) * 1000 + (p[2].toDouble() * 1000).toLong())
                    else (begin.removeSuffix("s").toDouble() * 1000).toLong()
                } else m.groupValues[2].toLong()
                add(ms, m.groupValues[3].replace(Regex("<br\\s*/?>"), "\n"))
            }
        }
        return out.sortedBy { it.timeMs }
    }

    // ---------------------------------------------------------------- parsing

    private val WORD_TAG = Regex("<\\d+:\\d+(?:[.:]\\d+)?>") // enhanced-LRC per-word stamps
    private val TS = Regex("\\[(\\d+):(\\d+)(?:[.:](\\d+))?]")

    private fun parseLrc(lrc: String): List<Line> {
        if (lrc.isBlank()) return emptyList()
        val out = ArrayList<Line>()
        for (raw in lrc.lines()) {
            val stamps = TS.findAll(raw).toList()
            if (stamps.isEmpty()) continue
            val text = raw.substring(stamps.last().range.last + 1).replace(WORD_TAG, "").trim()
            for (m in stamps) {
                val min = m.groupValues[1].toLong()
                val s = m.groupValues[2].toLong()
                val frac = m.groupValues[3]
                val ms = if (frac.isEmpty()) 0L else (frac.padEnd(3, '0').take(3)).toLong()
                out += Line(min * 60_000 + s * 1000 + ms, text)
            }
        }
        return out.sortedBy { it.timeMs }
    }

    /** YouTube titles are noisy ("Artist - Song (Official Video)", channel "Artist - Topic"). */
    private fun guess(title: String, artist: String): Pair<String, String> {
        var t = title
        var a = artist.replace(Regex("(?i)\\s*-\\s*topic$"), "").replace(Regex("(?i)vevo$"), "").trim()
        val dash = t.indexOf(" - ")
        if (dash > 0) { // "Artist - Song"
            a = t.substring(0, dash).trim()
            t = t.substring(dash + 3)
        }
        t = t.replace(Regex("\\(.*?\\)|\\[.*?]"), " ")
            .replace(Regex("(?i)\\b(official|video|audio|lyrics?|lirik|mv|hd|hq)\\b"), " ")
            .replace(Regex("\\s+"), " ").trim()
        return t to a
    }
}
